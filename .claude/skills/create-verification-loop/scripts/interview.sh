#!/usr/bin/env bash
# Interview a repository, not a person: a deterministic inventory of what decides how its
# verification loop should look. Prints Markdown on stdout. Read-only; runs nothing of the
# repo's own (no install, no tests). Needs git and standard Unix tools only.
#
#   interview.sh [REPO]        REPO defaults to the current directory
set -uo pipefail

REPO="${1:-.}"
cd "$REPO" 2>/dev/null || { echo "interview: $REPO is not a directory" >&2; exit 1; }
REPO="$(pwd -P)"

has() { [ -e "$1" ]; }
tracked() { git ls-files --error-unmatch -- "$1" >/dev/null 2>&1; }
section() { printf '\n## %s\n\n' "$1"; }
row() { printf '| %s | %s |\n' "$1" "$2"; }
first_hit() { # first_hit <glob...>: the first existing path among the args, or nothing
  local p; for p in "$@"; do [ -e "$p" ] && { printf '%s\n' "$p"; return 0; }; done; return 1
}
count_files() { git ls-files -- "$@" 2>/dev/null | wc -l | tr -d ' '; }
grep_tracked() { # grep_tracked ERE [pathspec...]: matching tracked files, capped
  git grep -lE "$1" -- "${@:2}" 2>/dev/null | head -20
}

echo "# Repository interview: $REPO"
echo
echo "Generated by create-verification-loop/scripts/interview.sh on $(date -u +%Y-%m-%dT%H:%MZ). Facts only; judgement is the reader's."

section "Git"
if git rev-parse --is-inside-work-tree >/dev/null 2>&1; then
  echo "| Fact | Value |"; echo "|---|---|"
  row "toplevel" "$(git rev-parse --show-toplevel)"
  row "branch" "$(git rev-parse --abbrev-ref HEAD 2>/dev/null || echo detached)"
  row "default branch (origin)" "$(git symbolic-ref -q --short refs/remotes/origin/HEAD 2>/dev/null | sed 's#origin/##' || echo unknown)"
  row "remotes" "$(git remote -v 2>/dev/null | awk '{print $1" "$2}' | sort -u | tr '\n' ';' | sed 's/;$//')"
  row "tracked files" "$(git ls-files | wc -l | tr -d ' ')"
  row "commits" "$(git rev-list --count HEAD 2>/dev/null || echo 0)"
  row "dirty" "$([ -n "$(git status --porcelain 2>/dev/null)" ] && echo yes || echo no)"
  row "worktrees" "$(git worktree list 2>/dev/null | wc -l | tr -d ' ')"
  row "git hooks dir" "$(git config core.hooksPath 2>/dev/null || echo .git/hooks)"
else
  echo "Not a git repository. The hooks, fingerprint and PR path all need one: \`git init\` first."
fi

section "Ecosystems (manifests found)"
echo "| Ecosystem | Manifest | Lockfile | Package manager hints |"; echo "|---|---|---|---|"
has package.json && row_pm() { :; }
if has package.json; then
  lock="$(first_hit pnpm-lock.yaml package-lock.json yarn.lock bun.lockb bun.lock || echo none)"
  pm="$(grep -oE '"packageManager"[[:space:]]*:[[:space:]]*"[^"]+"' package.json | head -1 | cut -d'"' -f4)"
  ws="$(has pnpm-workspace.yaml && echo 'pnpm workspace;' ; grep -q '"workspaces"' package.json 2>/dev/null && echo 'npm/yarn workspaces')"
  printf '| node | package.json | %s | %s %s |\n' "$lock" "${pm:-}" "${ws:-}"
fi
if has pyproject.toml || has setup.py || has requirements.txt; then
  m="$(first_hit pyproject.toml setup.py requirements.txt)"
  lock="$(first_hit uv.lock poetry.lock Pipfile.lock requirements.lock pdm.lock || echo none)"
  tool="$(grep -oE '^\[tool\.(uv|poetry|pdm|hatch|setuptools|pytest|ruff|mypy|pyright)[^]]*\]' pyproject.toml 2>/dev/null | tr '\n' ' ')"
  printf '| python | %s | %s | %s |\n' "$m" "$lock" "${tool:-}"
fi
has go.mod && printf '| go | go.mod | %s | go %s |\n' "$(first_hit go.sum || echo none)" "$(grep -E '^go ' go.mod | awk '{print $2}')"
has Cargo.toml && printf '| rust | Cargo.toml | %s | %s |\n' "$(first_hit Cargo.lock || echo none)" "$(grep -q '^\[workspace\]' Cargo.toml && echo workspace)"
has Gemfile && printf '| ruby | Gemfile | %s | %s |\n' "$(first_hit Gemfile.lock || echo none)" "$(has .ruby-version && echo ".ruby-version=$(cat .ruby-version)")"
{ has pom.xml || has build.gradle || has build.gradle.kts; } && printf '| jvm | %s | %s | |\n' "$(first_hit pom.xml build.gradle.kts build.gradle)" "$(first_hit gradle.lockfile || echo none)"
{ ls ./*.csproj ./*.sln >/dev/null 2>&1 || has global.json; } && printf '| dotnet | %s | %s | |\n' "$(ls ./*.sln ./*.csproj 2>/dev/null | head -1)" "$(first_hit packages.lock.json || echo none)"
has composer.json && printf '| php | composer.json | %s | |\n' "$(first_hit composer.lock || echo none)"
has mix.exs && printf '| elixir | mix.exs | %s | |\n' "$(first_hit mix.lock || echo none)"
has Makefile && printf '| make | Makefile | - | targets: %s |\n' "$(grep -oE '^[a-zA-Z_-]+:' Makefile | tr -d ':' | head -15 | tr '\n' ' ')"
has justfile && printf '| just | justfile | - | %s |\n' "$(grep -oE '^[a-zA-Z_-]+:' justfile | tr -d ':' | head -15 | tr '\n' ' ')"
has Taskfile.yml && printf '| task | Taskfile.yml | - | |\n'

section "Toolchain pins"
echo "| File | Content (first lines) |"; echo "|---|---|"
for f in mise.toml .mise.toml .tool-versions .nvmrc .node-version .python-version .ruby-version .java-version rust-toolchain.toml rust-toolchain global.json .go-version; do
  has "$f" && row "$f" "$(head -5 "$f" | tr '\n' ' ' | cut -c1-120)"
done
if has package.json; then
  e="$(grep -oE '"engines"[^}]*}' package.json | head -1)"; [ -n "$e" ] && row "package.json engines" "$e"
fi
has pyproject.toml && { rp="$(grep -E '^requires-python' pyproject.toml)"; [ -n "$rp" ] && row "pyproject requires-python" "$rp"; }

section "Scripts and commands the repo already names"
if has package.json; then
  echo '```json'; echo "// package.json scripts"
  awk '/"scripts"[[:space:]]*:/{f=1} f{print} f&&/^[[:space:]]*}/{exit}' package.json
  echo '```'
fi
if has pyproject.toml; then
  echo '```toml'; echo "# pyproject.toml tool sections"
  grep -E '^\[tool\.' pyproject.toml; echo '```'
fi
if has Makefile; then
  echo '```make'; echo "# Makefile targets (first 40 lines)"; grep -E '^[a-zA-Z_.-]+:' Makefile | head -40; echo '```'
fi
for f in justfile Taskfile.yml; do has "$f" && { echo '```'; echo "# $f"; head -60 "$f"; echo '```'; }; done

section "Test, lint, type and build tooling detected"
echo "| Tool | Evidence |"; echo "|---|---|"
for pair in \
  "vitest:vitest.config.* vitest.workspace.* package.json" \
  "jest:jest.config.* package.json" \
  "mocha:.mocharc.* package.json" \
  "playwright:playwright.config.*" \
  "cypress:cypress.config.*" \
  "pytest:pytest.ini pyproject.toml setup.cfg tox.ini conftest.py" \
  "tox:tox.ini" \
  "nox:noxfile.py" \
  "ruff:ruff.toml pyproject.toml" \
  "mypy:mypy.ini pyproject.toml setup.cfg" \
  "pyright:pyrightconfig.json pyproject.toml" \
  "eslint:eslint.config.* .eslintrc*" \
  "biome:biome.json biome.jsonc" \
  "prettier:.prettierrc* prettier.config.*" \
  "tsc:tsconfig.json" \
  "knip:knip.json knip.jsonc knip.ts" \
  "dependency-cruiser:.dependency-cruiser.* .dependency-cruiser.cjs" \
  "stryker:stryker.config.* stryker.conf.*" \
  "golangci-lint:.golangci.yml .golangci.yaml .golangci.toml" \
  "clippy:clippy.toml .cargo/config.toml" \
  "rubocop:.rubocop.yml" \
  "rspec:.rspec spec" \
  "phpunit:phpunit.xml phpunit.xml.dist phpunit.dist.xml" \
  "phpstan:phpstan.neon phpstan.neon.dist phpstan.dist.neon" \
  "psalm:psalm.xml psalm.xml.dist" \
  "pint:pint.json" \
  "php-cs-fixer:.php-cs-fixer.php .php-cs-fixer.dist.php" \
  "laravel:artisan" \
  "expo:app.json app.config.js app.config.ts eas.json" \
  "react-native:metro.config.js ios android" \
  "detox:.detoxrc.js .detoxrc.json detox.config.js" \
  "maestro:.maestro" \
  "lefthook:lefthook.yml lefthook.yaml" \
  "husky:.husky" \
  "pre-commit:.pre-commit-config.yaml" \
  "docker:Dockerfile docker-compose.yml docker-compose.yaml compose.yml compose.yaml" \
  "devcontainer:.devcontainer" \
  "nix:flake.nix shell.nix" \
  "env-example:.env.example .env.sample .env.template" \
  "shellcheck:.shellcheckrc" \
  "editorconfig:.editorconfig"; do
  name="${pair%%:*}"; globs="${pair#*:}"; found=""
  for g in $globs; do
    for m in $g; do [ -e "$m" ] && found="$found $m"; done
  done
  # package.json evidence only counts when the tool is actually a dependency
  if [ -n "$found" ] && [[ "$found" == *package.json* ]] && ! grep -qE "\"$name\"" package.json 2>/dev/null; then found="${found// package.json/}"; fi
  # pyproject.toml evidence only counts when the tool has a [tool.<name>] section or is a dependency
  if [ -n "$found" ] && [[ "$found" == *pyproject.toml* ]] && ! grep -qE "^\[tool\.${name}(\.|\])|[\"\x27]${name}[\"\x27>=<\[ ]" pyproject.toml 2>/dev/null; then found="${found// pyproject.toml/}"; fi
  [ -n "${found// /}" ] && row "$name" "$(echo $found)"
done
if has package.json; then
  deps="$(grep -oE '"(vitest|jest|mocha|playwright|@playwright/test|cypress|eslint|@biomejs/biome|prettier|typescript|knip|dependency-cruiser|@stryker-mutator/core|husky|lefthook|tsx|ts-node|turbo|nx|react-native|expo|detox)"' package.json | sort -u | tr -d '"' | tr '\n' ' ')"
  [ -n "$deps" ] && row "package.json devDependencies of note" "$deps"
fi

section "Tests on disk"
echo "| Pattern | Files |"; echo "|---|---|"
row '*.test.* / *.spec.*' "$(count_files '*.test.*' '*.spec.*' '*_test.go' '*_spec.rb' 'test_*.py' '*_test.py')"
row "test/ tests/ spec/ __tests__/ e2e/ dirs" "$(for d in test tests spec __tests__ e2e; do [ -d "$d" ] && printf '%s(%s) ' "$d" "$(git ls-files -- "$d" | wc -l | tr -d ' ')"; done)"
row "retry settings in test configs" "$(grep_tracked '\b(retry|retries)\b[[:space:]]*[:=]' '*.config.*' 'pytest.ini' 'pyproject.toml' '*.toml' | tr '\n' ' ')"
row "skipped/only/todo markers" "$(git grep -nE '\.(skip|only|todo)\(|@pytest\.mark\.skip|#\[ignore\]|t\.Skip\(|xit\(|xdescribe\(' -- . ':(exclude)node_modules' 2>/dev/null | wc -l | tr -d ' ') lines"
row "TODO/FIXME" "$(git grep -nE '\b(TODO|FIXME|XXX|HACK)\b' -- . ':(exclude)*.md' ':(exclude)node_modules' 2>/dev/null | wc -l | tr -d ' ') lines"
row "sleeps in tests" "$(git grep -nE 'setTimeout\([^,]*,[[:space:]]*[0-9]{3,}|time\.sleep\(|sleep\([0-9]|Thread\.sleep' -- 'test*' 'tests*' 'spec*' 'e2e*' '*.test.*' '*.spec.*' 2>/dev/null | wc -l | tr -d ' ') lines"
row "mocking libs referenced" "$(git grep -lE 'vi\.mock\(|jest\.mock\(|unittest\.mock|from mock import|sinon|gomock|mockito' -- . ':(exclude)node_modules' 2>/dev/null | wc -l | tr -d ' ') files"

section "Services and environment the code needs"
echo "| Signal | Evidence |"; echo "|---|---|"
row "compose services" "$(for f in docker-compose.yml docker-compose.yaml compose.yml compose.yaml; do has $f && grep -E '^[[:space:]]{2}[a-zA-Z0-9_-]+:' $f | tr -d ' :' | tr '\n' ' '; done)"
env_pat=$'process\\.env\\.[A-Z0-9_]+|os\\.environ(\\.get)?\\[?\\(?["\'][A-Z0-9_]+|os\\.Getenv\\("[A-Z0-9_]+|ENV\\["[A-Z0-9_]+|std::env::var\\("[A-Z0-9_]+'
env_vars="$(git grep -ohE "$env_pat" -- . ':(exclude)node_modules' 2>/dev/null | grep -oE '[A-Z][A-Z0-9_]{2,}' | sort | uniq -c | sort -rn | head -25 | awk '{printf "%s(%s) ", $2, $1}')"
row "env vars read in code" "$env_vars"
row "database drivers" "$(git grep -lE 'pg\b|postgres|mysql|sqlite|mongodb|redis|prisma|drizzle|sqlalchemy|typeorm|knex|sequelize|gorm|diesel|sqlx|activerecord' -- 'package.json' 'pyproject.toml' 'go.mod' 'Cargo.toml' 'Gemfile' 'requirements*.txt' 2>/dev/null | tr '\n' ' ')"
row "network/LLM credentials in env example" "$(for f in .env.example .env.sample .env.template; do has $f && grep -oE '^[A-Z0-9_]*(KEY|TOKEN|SECRET|PASSWORD|URL)[A-Z0-9_]*' $f | tr '\n' ' '; done)"
port_pat=$'\\b(PORT|port)[[:space:]]*[:=]+[[:space:]]*["\']?[0-9]{4,5}|localhost:[0-9]{4,5}|:[0-9]{4,5}"'
ports="$(git grep -ohE "$port_pat" -- . ':(exclude)node_modules' ':(exclude)*.lock' 2>/dev/null | grep -oE '[0-9]{4,5}' | sort -u | head -15 | tr '\n' ' ')"
row "ports in code/config" "$ports"

section "CI and automation"
echo "| Item | Evidence |"; echo "|---|---|"
if [ -d .github/workflows ]; then
  for w in .github/workflows/*.y*ml; do
    row "$w" "on: $(grep -E '^on:|^  (push|pull_request|workflow_dispatch|schedule)' "$w" | tr -d ' \n' | cut -c1-80); jobs: $(awk '/^jobs:/{f=1;next} f&&/^  [a-zA-Z0-9_-]+:/{gsub(/[ :]/,"");printf "%s ", $0}' "$w")"
  done
else
  row "GitHub Actions" "none"
fi
has .gitlab-ci.yml && row ".gitlab-ci.yml" "present"
has Jenkinsfile && row "Jenkinsfile" "present"
has .circleci/config.yml && row "CircleCI" "present"
has .github/pull_request_template.md && row "PR template" ".github/pull_request_template.md"
has .github/CODEOWNERS && row "CODEOWNERS" "present"
has .github/dependabot.yml && row "dependabot" "present"
has renovate.json && row "renovate" "present"
row "branch protection" "unknown from disk; check with: gh api repos/{owner}/{repo}/branches/<default>/protection"

section "Issue tracker (for the PR tracker rule)"
echo "| Item | Evidence |"; echo "|---|---|"
# Project keys: KEY-<n> as a branch-name segment or a commit-subject prefix. Ignore versions,
# charsets and years that look the same.
keys="$( { git for-each-ref --format='%(refname:short)' refs/heads refs/remotes 2>/dev/null | sed 's#^[^/]*/##' | tr '/' '\n'
          git log -n 200 --format='%s' 2>/dev/null | sed -n 's/^[[]*\([A-Za-z][A-Za-z0-9]*-[0-9][0-9]*\).*/\1/p'
        } | sed -n 's/^\([A-Za-z][A-Za-z0-9]*\)-[0-9][0-9]*\(-.*\)\{0,1\}$/\1/p' | tr 'a-z' 'A-Z' \
        | grep -vE '^(UTF|ISO|COVID|SHA|MD|NODE|PYTHON|PY|V|RC|CVE|HTTP|ES|TLS|SSL|IPV|X|ARM|AMD|OS|IOS)$' | sort | uniq -c | sort -rn | head -5 | tr -s ' ' | tr '\n' ';')"
row "key candidates (count KEY)" "${keys:-none seen in branches or the last 200 commit subjects}"
tr_hits="$(grep -rilE 'linear\.app|atlassian\.net|jira|plane\.so|app\.plane|shortcut\.com|clickup' --include='*.md' --include='*.yml' --include='*.yaml' --include='*.json' . 2>/dev/null | grep -v node_modules | head -3 | tr '\n' ' ')"
row "tracker named in docs/config" "${tr_hits:-none}"
git log -n 200 --format='%s' 2>/dev/null | grep -qE '(^|[^0-9])#[0-9]+' && row "GitHub issue refs in commits" "yes (#n); GitHub Issues is likely the tracker"
echo
echo "Set BRANCH_KEYS in scripts/tracker.py to the keys that are real project keys; leave it empty"
echo "when none are (branch names are then never read)."

section "Agent instructions and Claude Code setup already present"
echo "| File | Lines | Notes |"; echo "|---|---|---|"
for f in AGENTS.md CLAUDE.md CONTEXT.md CONTRIBUTING.md README.md GEMINI.md .cursorrules .cursor/rules .windsurfrules docs/agent.md docs/agents.md; do
  if [ -e "$f" ]; then
    n="$(cat "$f" 2>/dev/null | wc -l | tr -d ' ')"
    note=""
    [ "$f" = CLAUDE.md ] && grep -q '^@AGENTS.md' CLAUDE.md && note="imports AGENTS.md"
    printf '| %s | %s | %s |\n' "$f" "$n" "$note"
  fi
done
if [ -d .claude ]; then
  printf '| .claude/ | | %s |\n' "$(find .claude -maxdepth 2 -mindepth 1 \( -type f -o -type d -o -type l \) | sed 's#^\.claude/##' | tr '\n' ' ' | cut -c1-200)"
  has .claude/settings.json && printf '| .claude/settings.json hooks | | %s |\n' "$(grep -oE '"(SessionStart|UserPromptSubmit|PreToolUse|PostToolUse|PreCompact|Stop|SubagentStop|TaskCompleted|Notification)"' .claude/settings.json | tr -d '"' | sort -u | tr '\n' ' ')"
  [ -d .claude/rules ] && printf '| .claude/rules | | %s |\n' "$(ls -la .claude/rules | awk 'NR>3{printf "%s%s ", $9, ($11?" -> "$11:"")}')"
  [ -d .claude/skills ] && printf '| .claude/skills | | %s |\n' "$(ls .claude/skills | tr '\n' ' ')"
  [ -d .claude/commands ] && printf '| .claude/commands | | %s |\n' "$(ls .claude/commands | tr '\n' ' ')"
fi
[ -d docs ] && printf '| docs/ | | %s files; subdirs: %s |\n' "$(git ls-files -- docs | wc -l | tr -d ' ')" "$(find docs -maxdepth 1 -mindepth 1 -type d | sed 's#docs/##' | tr '\n' ' ')"
row_frontmatter="$(git grep -lE '^paths:' -- '*.md' 2>/dev/null | tr '\n' ' ')"
[ -n "$row_frontmatter" ] && printf '| docs with `paths:` frontmatter | | %s |\n' "$row_frontmatter"

section "Existing verification artefacts"
echo "| Item | Evidence |"; echo "|---|---|"
row "one gate command" "$(has package.json && grep -oE '"(verify|check|ci|validate|gate)[^"]*"[[:space:]]*:' package.json | tr -d '": ' | tr '\n' ' '; has Makefile && grep -oE '^(verify|check|ci|validate|gate|test)[a-z-]*:' Makefile | tr -d ':' | tr '\n' ' ')"
row "init / bootstrap script" "$(ls init.sh bootstrap.sh setup.sh scripts/setup* scripts/bootstrap* script/setup script/bootstrap bin/setup 2>/dev/null | tr '\n' ' ')"
row "baseline / ratchet files" "$(ls verify-baseline.json .verify ratchet* coverage-baseline* 2>/dev/null | tr '\n' ' ')"
row "coverage config" "$(git grep -lE 'coverage' -- '*.config.*' 'pyproject.toml' 'setup.cfg' '.coveragerc' 'tox.ini' 2>/dev/null | tr '\n' ' ')"
row "untracked files a setup depends on" "$(git ls-files --others --exclude-standard 2>/dev/null | grep -iE 'lock|\.env\.example|\.nvmrc|\.tool-versions|\.python-version' | tr '\n' ' ')"
row "tracked runtime state (exclude from the fingerprint, or gitignore)" "$(git ls-files -- 'tmp/*' 'log/*' 'storage/*' '*.sqlite3' '*.sqlite3-*' '*.log' 'config/master.key' '.env' 'coverage/*' 'node_modules/*' 'vendor/bundle/*' '__pycache__/*' '*.pyc' 2>/dev/null | sed -E 's#^([^/]+/[^/]+)/.*#\1/…#' | sort -u | head -12 | tr '\n' ' ')"
row "gitignored build/report dirs" "$(has .gitignore && grep -vE '^#|^$' .gitignore | head -15 | tr '\n' ' ')"

section "Size and shape"
echo "| Measure | Value |"; echo "|---|---|"
row "source files by extension" "$(git ls-files | sed -nE 's/.*\.([a-zA-Z0-9]+)$/\1/p' | sort | uniq -c | sort -rn | head -12 | awk '{printf "%s:%s ", $2, $1}')"
row "largest files (lines)" "$(git ls-files -- '*.ts' '*.tsx' '*.js' '*.mjs' '*.py' '*.go' '*.rs' '*.rb' '*.java' '*.kt' '*.cs' 2>/dev/null | grep -vE 'node_modules|vendor|dist/|build/|\.min\.' | xargs -r wc -l 2>/dev/null | sort -rn | sed -n '2,6p' | awk '{printf "%s(%s) ", $2, $1}')"
row "top-level dirs" "$(find . -maxdepth 1 -mindepth 1 -type d -not -name '.*' -not -name node_modules | sed 's#\./##' | sort | tr '\n' ' ')"

section "What to read next (by hand)"
cat <<'EOF'
- README and CONTRIBUTING: the documented setup and test commands, in the words the repo uses.
- The CI workflow(s): what already counts as the gate, and on which events.
- The test runner config: reporters available (JSON, JUnit), coverage provider, retries, timeouts.
- The manifest scripts: which commands exist and which are missing (lint, typecheck, test, build, dead code).
- Any existing AGENTS.md/CLAUDE.md: keep its voice and facts; do not replace it, extend it.
EOF
